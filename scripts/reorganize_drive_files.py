def get_file_hash(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        while chunk := f.read(8192):
            h.update(chunk)
    return h.hexdigest()

def clean_filename(fname):
    """ファイル名のゴミ・実体参照・サイズ表記等を綺麗にクレンジング"""
    if fname in SPECIAL_RENAMES:
        return SPECIAL_RENAMES[fname]

    ext = os.path.splitext(fname)[1]
    name = os.path.splitext(fname)[0]

    # 1. HTML実体参照
    name = name.replace("&emsp;", " ").replace("&nbsp;", " ")

    # 2. サイズ表記・PDF表記の削除
    name = re.sub(r'\[[0-9,.]+\s*[KM]B\]', '', name)
    name = re.sub(r'［[0-9,.]+\s*[KM]B］', '', name)
    name = re.sub(r'\([0-9,.]+\s*[KM]B\)', '', name)
    name = re.sub(r'\(PDF\s*[:_]\s*[0-9,.]+\s*[KM]B\)', '', name, flags=re.IGNORECASE)
    name = re.sub(r'\[PDF\s*[0-9,.]+\s*[KM]B\]', '', name, flags=re.IGNORECASE)

    # 3. 不要なプレフィックスの変換
    if name.startswith("公的機関_"):
        raw_tail = name[len("公的機関_"):]
        if any(w in raw_tail for w in ["三次調整力", "コンプライアンス", "送配電", "需給ひっ迫", "節電", "災害時連携計画", "保全高度化"]):
            name = "TDGC_" + raw_tail
        elif "エネルギー基本計画" in raw_tail:
            name = "経産省_" + raw_tail
        else:
            name = "公的機関_" + raw_tail

    if name.startswith("送配電事業者_"):
        raw_tail = name[len("送配電事業者_"):]
        raw_tail = re.sub(r'^[・\s]+', '', raw_tail)
        if "東北電力" in raw_tail:
            name = "東北電力NW_" + raw_tail
        elif "関西電力" in raw_tail:
            name = "関西電力送配電_" + raw_tail
        elif "沖縄電力" in raw_tail:
            name = "沖縄電力_" + raw_tail
        elif "東京電力" in raw_tail:
            name = "東京電力PG_" + raw_tail
        elif "四国電力" in raw_tail:
            name = "四国電力送配電_" + raw_tail
        elif "中国電力" in raw_tail:
            name = "中国電力NW_" + raw_tail
        else:
            name = "送配電各社_" + raw_tail

    # 先頭の中黒
    name = re.sub(r'^[・\s]+', '', name)

    # アンダースコアやスペースの重複を解消
    name = re.sub(r'\s+', ' ', name)
    name = re.sub(r'_+', '_', name)
    name = name.strip(' _')

    return name + ext

def main():
    print("=" * 70)
    print(" 🚀 Google Drive ファイル名・フォルダ構成 一括整理・最適化 実行")
    print("=" * 70)

    if not os.path.isdir(BASE_DIR):
        print(f"❌ エラー: 対象ディレクトリが存在しません: {BASE_DIR}")
        sys.exit(1)

    # 全ファイルをスキャンして移動計画を作成
    plan = []
    for root, dirs, files in os.walk(BASE_DIR):
        rel_root = os.path.relpath(root, BASE_DIR)
        if rel_root == "." or rel_root.startswith("HPバックアップ") or ".git" in rel_root:
            continue

        target_rel_folder = FOLDER_MAP.get(rel_root, rel_root)
        target_abs_folder = os.path.join(BASE_DIR, target_rel_folder)

        for f in files:
            src_path = os.path.join(root, f)
            new_fname = clean_filename(f)
            dest_path = os.path.join(target_abs_folder, new_fname)

            plan.append({
                "src_path": src_path,
                "dest_folder": target_abs_folder,
                "orig_fname": f,
                "new_fname": new_fname,
                "dest_path": dest_path
            })

    print(f"総対象ファイル数: {len(plan)} 件")

    # 宛先パス衝突の解決（万が一の連番付与および完全重複削除）
    dest_tracker = {}
    actions = []
    
    for item in plan:
        target = item["dest_path"]
        src = item["src_path"]

        # もし全く同じ宛先が既に登録されている場合
        if target in dest_tracker:
            prev_src = dest_tracker[target]["src_path"]
            # ハッシュ比較
            if get_file_hash(src) == get_file_hash(prev_src):
                print(f"🗑️ 完全重複ファイル（ハッシュ同一）を検出 -> 削除対象: {os.path.basename(src)}")
                actions.append({
                    "action": "delete_duplicate",
                    "src_path": src,
                    "target_path": None,
                    "reason": f"Duplicate of {prev_src}"
                })
                continue
            else:
                # 異なる内容なら連番サフィックス付与
                ext = os.path.splitext(item["new_fname"])[1]
                stem = os.path.splitext(item["new_fname"])[0]
                idx = 2
                while True:
                    alt_fname = f"{stem}_{idx}{ext}"
                    alt_dest = os.path.join(item["dest_folder"], alt_fname)
                    if alt_dest not in dest_tracker and not os.path.exists(alt_dest):
                        target = alt_dest
                        item["new_fname"] = alt_fname
                        item["dest_path"] = alt_dest
                        break
                    idx += 1
                print(f"⚠️ 別内容ファイルの同名衝突回避 -> 新ファイル名: {alt_fname}")

        dest_tracker[target] = item
        actions.append({
            "action": "move_rename",
            "src_path": src,
            "target_path": target,
            "orig_fname": item["orig_fname"],
            "new_fname": item["new_fname"]
        })

    # 実行
    moved_count = 0
    renamed_count = 0
    deleted_count = 0

    print("\n📦 ファイル移動・リネーム処理を開始...")
    for act in actions:
        if act["action"] == "delete_duplicate":
            try:
                os.remove(act["src_path"])
                deleted_count += 1
            except Exception as e:
                print(f"❌ 削除失敗: {act['src_path']} -> {e}")
        elif act["action"] == "move_rename":
            src = act["src_path"]
            tgt = act["target_path"]
            os.makedirs(os.path.dirname(tgt), exist_ok=True)
            
            if src != tgt:
                try:
                    shutil.move(src, tgt)
                    if os.path.dirname(src) != os.path.dirname(tgt):
                        moved_count += 1
                    if os.path.basename(src) != os.path.basename(tgt):
                        renamed_count += 1
                except Exception as e:
                    print(f"❌ 移動失敗: {src} -> {tgt}: {e}")

    print(f"✅ 移動完了: フォルダ間移動 {moved_count} 件 / リネーム {renamed_count} 件 / 重複削除 {deleted_count} 件")

    # 空ディレクトリのクリーンアップ（ボトムアップ）
    print("\n🧹 空フォルダのクリーンアップ...")
    removed_dirs = 0
    for root, dirs, files in os.walk(BASE_DIR, topdown=False):
        rel = os.path.relpath(root, BASE_DIR)
        if rel == "." or rel.startswith("HPバックアップ") or ".git" in rel:
            continue
        try:
            if not os.listdir(root):
                os.rmdir(root)
                print(f"  削除した空フォルダ: {rel}")
                removed_dirs += 1
        except Exception as e:
            pass

    print(f"✅ 空フォルダ削除完了: {removed_dirs} 件")
    print("=" * 70)
    print(" 🎉 全体の整理・最適化が正常に完了しました！")
    print("=" * 70)

if __name__ == "__main__":
    main()
